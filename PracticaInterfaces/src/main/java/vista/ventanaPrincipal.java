    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   
        String nombre = jIngresarn1.getText().trim();
        String edad = jTextField2.getText().trim();
        String correo = jTextField3.getText().trim();
        
    JOptionPane.showMessageDialog(
          this,
                "nombre: "+nombre+
                        "\nEdad: "+edad+
                        "\nCorreo: "+correo);
    
            
            if(nombre.isEmpty() || edad.isEmpty() || correo.isEmpty()) {
     JOptionPane.showMessageDialog(
     this,
             "todos los campos son obligatorios",
             "advertencia",
             JOptionPane.WARNING_MESSAGE
     
     );
     
     return;
 }
     
            int edadNumero;
            
            try {
                edadNumero = Integer.parseInt(edad);
                
            }catch (NumberFormatException e){
                JOptionPane.showMessageDialog(
                this,
                        "la edad deber ser un numero",
                        "Error",
                JOptionPane.ERROR_MESSAGE
                );
                return;
            }
            
          JOptionPane.showMessageDialog(
                this,
                  "Estudiante registrado correctamente\n"+
                          "nombre: "+nombre+
                          "\nEdad: "+edadNumero+
                          "\nCorreo: "+correo,
                          "Registro exitoso",
                          JOptionPane.INFORMATION_MESSAGE
          );
          
          modelo.addRow(new Object[]{
              nombre,
              edadNumero,
              correo
          });
          
           JOptionPane.showMessageDialog(
                this,
                   "Estudiante agregado correctamente"
           );
      jIngresarn1.setText("");
jTextField2.setText("");
jTextField3.setText("");
    
    }//GEN-LAST:event_jButton1ActionPerformed

